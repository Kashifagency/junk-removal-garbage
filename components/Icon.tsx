// Map Font Awesome names used in Elementor to local icons.
export function iconFromFa(fa: string, fallback: IconName = 'checkCircle'): IconName {
  if (/map-marker/.test(fa)) return 'pin';
  if (/envelope/.test(fa)) return 'mail';
  if (/phone/.test(fa)) return 'phone';
  return fallback;
}
